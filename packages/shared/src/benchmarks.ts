/**
 * Normalizes a raw benchmark item into a TransportOption for client presentation.
 */
function toTransportOption(item: RawBenchmarkItem): TransportOption {
  return {
    id: item.id,
    mode: item.mode,
    category: item.category,
    operator: item.operator,
    identifier: item.identifier,
    departureTime: item.departureTime,
    arrivalTime: item.arrivalTime,
    durationMinutes: item.durationMinutes,
    originHub: item.originHubName,
    destinationHub: item.destHubName,
    baseFareInr: item.baseFareInr,
    taxesAndFeesInr: item.taxesAndFeesInr,
    totalCostInr: item.totalCostInr,
    availableSeats: item.availableSeats,
    seatClass: item.seatClass,
    attribution: {
      provider: item.provider,
      displayName: item.operator,
      officialBookingUrl: item.officialBookingUrl,
      lastCheckedTimestamp: new Date().toISOString(),
      isDemonstrationData: true,
      dataSource: 'DEMO',
      notes: item.notes,
    },
    transferDetails: item.firstMileCostInr
      ? {
          firstMileEstMinutes: item.firstMileEstMinutes || 30,
          firstMileCostInr: item.firstMileCostInr,
          lastMileEstMinutes: item.lastMileEstMinutes || 25,
          lastMileCostInr: item.lastMileCostInr || 80,
          description: item.transferNotes || 'Transfer to/from hub',
        }
      : undefined,
  };
}

/**
 * Inverts a forward offer to create an authentic return-direction benchmark offer.
 */
function createReverseOffer(item: RawBenchmarkItem): RawBenchmarkItem {
  // Compute approximate return schedule times
  let returnDep = '08:00 AM';
  let returnArr = '11:00 AM';

  if (item.mode === 'FLIGHT') {
    returnDep = '02:30 PM';
    const arrHours = Math.floor(item.durationMinutes / 60);
    const arrMins = item.durationMinutes % 60;
    returnArr = `${String(2 + arrHours + 12).padStart(2, '0')}:${String(30 + arrMins).padStart(2, '0')}`;
  } else if (item.mode === 'TRAIN') {
    returnDep = '05:30 PM';
    returnArr = '08:45 AM';
  } else if (item.mode === 'BUS') {
    returnDep = '08:30 PM';
    returnArr = '06:00 AM';
  }

  return {
    ...item,
    id: `${item.id}-rev`,
    departureTime: returnDep,
    arrivalTime: returnArr,
    originHubCode: item.destHubCode,
    originHubName: item.destHubName,
    destHubCode: item.originHubCode,
    destHubName: item.originHubName,
    notes: `${item.notes} (Return service)`,
  };
}

/**
 * Finds the matching corridor definition between two city inputs.
 */
export function findCorridor(
  originInput: string,
  destInput: string
): { corridor: CorridorDefinition; isReverse: boolean } | null {
  const originLoc = resolveLocation(originInput);
  const destLoc = resolveLocation(destInput);

  if (!originLoc || !destLoc) {
    return null;
  }

  // Check forward corridors
  for (const c of CORRIDOR_BENCHMARKS) {
    if (c.originCityId === originLoc.id && c.destCityId === destLoc.id) {
      return { corridor: c, isReverse: false };
    }
  }

  // Check reverse corridors
  for (const c of CORRIDOR_BENCHMARKS) {
    if (c.originCityId === destLoc.id && c.destCityId === originLoc.id) {
      return { corridor: c, isReverse: true };
    }
  }

  return null;
}

/**
 * Checks whether a given city pair is supported in the curated benchmark catalog.
 */
export function isSupportedCorridor(originInput: string, destInput: string): boolean {
  return findCorridor(originInput, destInput) !== null;
}

/**
 * Retrieves all benchmark transport options for a route, supporting both directions.
 */
export function getCorridorBenchmarkOptions(
  originInput: string,
  destInput: string
): TransportOption[] {
  const match = findCorridor(originInput, destInput);
  if (!match) {
    return [];
  }

  const { corridor, isReverse } = match;

  if (!isReverse) {
    return corridor.forwardOffers.map(toTransportOption);
  }

  // If explicit reverse offers are defined, use them; otherwise invert forward offers
  if (corridor.reverseOffers && corridor.reverseOffers.length > 0) {
    return corridor.reverseOffers.map(toTransportOption);
  }

  return corridor.forwardOffers.map(createReverseOffer).map(toTransportOption);
}

/**
 * Returns raw benchmark items filtered by travel mode.
 */
export function getRawCorridorOffersByMode(
  mode: TravelMode,
  originInput: string,
  destInput: string
): RawBenchmarkItem[] {
  const match = findCorridor(originInput, destInput);
  if (!match) {
    return [];
  }

  const { corridor, isReverse } = match;
  let items: RawBenchmarkItem[] = [];

  if (!isReverse) {
    items = corridor.forwardOffers;
  } else if (corridor.reverseOffers && corridor.reverseOffers.length > 0) {
    items = corridor.reverseOffers;
  } else {
    items = corridor.forwardOffers.map(createReverseOffer);
  }

  return items.filter((o) => o.mode === mode);
}

/**
 * Returns a human-readable list of all supported benchmark corridors.
 */
export function getSupportedCorridorsList(): string[] {
  return CORRIDOR_BENCHMARKS.map(
    (c) => `${c.originCityName} ↔ ${c.destCityName}`
  );
}
