export class CuratedPlacesProvider implements IPlacesProvider {
  readonly providerName = 'CURATED_PLACES_PROVIDER';

  async getPlaces(destination: string, category?: ActivityCategory): Promise<PlaceItem[]> {
    const cleanDest = destination.split('(')[0].trim().toLowerCase().replace(/[^a-z]/g, '');

    const places = VERIFIED_DESTINATION_PLACES.filter((p) => {
      const pDest = p.destination.toLowerCase().replace(/[^a-z]/g, '');
      return cleanDest.includes(pDest) || pDest.includes(cleanDest);
    });

    if (category) {
      const filtered = places.filter((p) => p.category === category);
      if (filtered.length > 0) return filtered;
    }

    return places;
  }

  async getPlaceById(id: string): Promise<PlaceItem | null> {
    const place = VERIFIED_DESTINATION_PLACES.find((p) => p.id === id);
    return place || null;
  }
}
